'use strict';
/* global __dirname */

// Generates src/data/clothesImages.ts from the images that actually exist on
// disk in assets/clothes/. Only emits a static require() for each <id>.jpg
// found, so the app never bundles a reference to a missing image.
//
// Usage:
//   node scripts/gen-images.js
//
// Can also be required as a module:
//   const { generateImagesTs } = require('./scripts/gen-images');
//   generateImagesTs();

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const ASSETS_DIR = path.join(ROOT, 'assets', 'clothes');
const IMAGES_TS_PATH = path.join(ROOT, 'src', 'data', 'clothesImages.ts');

function generateImagesTs() {
  if (!fs.existsSync(ASSETS_DIR)) {
    console.warn(`assets/clothes directory not found: ${ASSETS_DIR}`);
    return;
  }

  const files = fs.readdirSync(ASSETS_DIR);
  const ids = files
    .filter((f) => /^\d+\.jpg$/.test(f))
    .map((f) => Number(f.replace(/\.jpg$/, '')))
    .sort((a, b) => a - b);

  const lines = ids.map((id) => `  ${id}: require('../assets/clothes/${id}.jpg'),`);
  const content =
    '// Auto-generated by scripts/gen-images.js. Do not edit by hand.\n' +
    '// Maps each clothing id to its bundled local image (only for files that exist).\n' +
    'export const clothesImages: Record<number, number> = {\n' +
    lines.join('\n') +
    '\n};\n';
  fs.writeFileSync(IMAGES_TS_PATH, content, 'utf8');
  console.log(`Generated ${IMAGES_TS_PATH} with ${ids.length} image(s).`);
}

if (require.main === module) {
  generateImagesTs();
}

module.exports = { generateImagesTs };
