// Downloads bundled clothing images from the Pixabay API.
//
// Usage:
//   PIXABAY_API_KEY=your_key node scripts/fetch-images.js
//
// Reads PIXABAY_API_KEY from the environment. For every item in
// src/data/clothes.ts it searches Pixabay using the item's `query`,
// downloads the first unused hit's webformatURL (640 px wide) to
// assets/clothes/<id>.jpg, and writes src/data/clothesImages.ts with
// static requires for every item.
//
// Two items that share a query receive different hit indexes so their
// photos are not duplicated. If a query returns no hits, the script
// retries using just the item's `kind` word. It waits 700 ms between
// requests (Pixabay allows 100 per minute) and prints the ids that
// failed at the end.

'use strict';
/* global __dirname */

const fs = require('fs');
const path = require('path');
const https = require('https');

const ROOT = path.resolve(__dirname, '..');
const CLOTHES_PATH = path.join(ROOT, 'src', 'data', 'clothes.ts');
const ASSETS_DIR = path.join(ROOT, 'assets', 'clothes');
const IMAGES_TS_PATH = path.join(ROOT, 'src', 'data', 'clothesImages.ts');

const API_KEY = process.env.PIXABAY_API_KEY;
if (!API_KEY) {
  console.error('Error: PIXABAY_API_KEY environment variable is not set.');
  process.exit(1);
}

const DELAY_MS = 700;
const PER_PAGE = 10;

const BASE_URL =
  'https://pixabay.com/api/?' +
  `key=${encodeURIComponent(API_KEY)}` +
  `&image_type=photo&orientation=vertical&per_page=${PER_PAGE}&safesearch=true`;

// Parses src/data/clothes.ts to extract { id, kind, query } for each item.
// Each clothing entry lives on a single line, so a line-level regex is
// sufficient and keeps this script free of a TypeScript compiler dependency.
function loadClothes() {
  const text = fs.readFileSync(CLOTHES_PATH, 'utf8');
  const items = [];
  const lineRe =
    /id:\s*(\d+).*?kind:\s*'([^']*)'.*?query:\s*'([^']*)'/;
  for (const line of text.split('\n')) {
    const match = line.match(lineRe);
    if (match) {
      items.push({ id: Number(match[1]), kind: match[2], query: match[3] });
    }
  }
  return items;
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function jsonGet(url) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, (res) => {
      let data = '';
      res.on('data', (chunk) => {
        data += chunk;
      });
      res.on('end', () => {
        try {
          resolve(JSON.parse(data));
        } catch (err) {
          reject(new Error(`Invalid JSON from Pixabay: ${err.message}`));
        }
      });
    });
    req.on('error', reject);
  });
}

// Searches Pixabay and returns the hit list (possibly empty).
async function fetchHits(query) {
  const url = `${BASE_URL}&q=${encodeURIComponent(query)}`;
  const data = await jsonGet(url);
  return Array.isArray(data.hits) ? data.hits : [];
}

// Downloads a single image to `dest`. Resolves with dest on success.
function downloadImage(url, dest) {
  return new Promise((resolve, reject) => {
    const file = fs.createWriteStream(dest);
    const req = https.get(url, (res) => {
      if (res.statusCode !== 200) {
        res.resume();
        file.close();
        fs.unlink(dest, () => {});
        reject(new Error(`Pixabay returned HTTP ${res.statusCode}`));
        return;
      }
      res.pipe(file);
    });
    req.on('error', (err) => {
      file.close();
      fs.unlink(dest, () => {});
      reject(err);
    });
    file.on('error', (err) => {
      req.destroy();
      fs.unlink(dest, () => {});
      reject(err);
    });
    file.on('finish', () => {
      file.close();
      resolve(dest);
    });
  });
}

// Generates src/data/clothesImages.ts with static require() calls so the
// app can bundle the downloaded images without network access.
function writeImagesTs(ids) {
  const lines = ids
    .sort((a, b) => a - b)
    .map((id) => `  ${id}: require('../assets/clothes/${id}.jpg'),`);
  const content =
    '// Auto-generated by scripts/fetch-images.js. Do not edit by hand.\n' +
    '// Maps each clothing id to its bundled local image.\n' +
    'export const clothesImages: Record<number, number> = {\n' +
    lines.join('\n') +
    '\n};\n';
  fs.writeFileSync(IMAGES_TS_PATH, content, 'utf8');
}

async function main() {
  const items = loadClothes();
  if (items.length === 0) {
    console.error('No clothing items found in src/data/clothes.ts.');
    process.exit(1);
  }

  fs.mkdirSync(ASSETS_DIR, { recursive: true });

  // Tracks the next hit index to consume per query, so items sharing a
  // query receive distinct photos instead of duplicates.
  const hitIndexByQuery = {};
  const failed = [];

  for (const item of items) {
    let downloaded = false;
    // Try the specific query first, then fall back to the kind word.
    const queriesToTry =
      item.kind === item.query ? [item.query] : [item.query, item.kind];

    for (const query of queriesToTry) {
      let hits;
      try {
        hits = await fetchHits(query);
      } catch (err) {
        console.warn(`  id ${item.id}: query "${query}" request failed: ${err.message}`);
        await sleep(DELAY_MS);
        continue;
      }
      await sleep(DELAY_MS);

      if (hits.length === 0) {
        continue; // no hits — try the next query (kind fallback)
      }

      const idx = hitIndexByQuery[query] ?? 0;
      hitIndexByQuery[query] = idx + 1;

      if (idx >= hits.length) {
        continue; // this query is exhausted — try the next one
      }

      const imageUrl = hits[idx].webformatURL;
      const dest = path.join(ASSETS_DIR, `${item.id}.jpg`);
      try {
        await downloadImage(imageUrl, dest);
        downloaded = true;
        break;
      } catch (err) {
        console.warn(`  id ${item.id}: download failed for "${query}": ${err.message}`);
      }
    }

    if (!downloaded) {
      failed.push(item.id);
    }
  }

  writeImagesTs(items.map((item) => item.id));

  console.log(`\nProcessed ${items.length} item(s).`);
  if (failed.length > 0) {
    console.log('Failed ids:', failed.join(', '));
    process.exitCode = 1;
  } else {
    console.log('All images downloaded successfully.');
  }
}

main().catch((err) => {
  console.error('Fatal error:', err);
  process.exit(1);
});
